"""Перевод первичных баллов во вторичные (тестовые).

Шкала профильной математики. Меняется по годам — при смене таблицы
проверять её по официальному документу Рособрнадзора, а не по памяти.
"""

# первичный → тестовый
MATH_PROF_SCALE = {
    0: 0, 1: 6, 2: 11, 3: 17, 4: 22, 5: 27, 6: 34, 7: 40, 8: 46, 9: 52,
    10: 58, 11: 64, 12: 70, 13: 72, 14: 74, 15: 76, 16: 78, 17: 80,
    18: 82, 19: 84, 20: 86, 21: 88, 22: 90, 23: 92, 24: 94, 25: 95,
    26: 96, 27: 97, 28: 98, 29: 99, 30: 100, 31: 100, 32: 100,
}

MAX_PRIMARY = max(MATH_PROF_SCALE)


def secondary_score(primary: int, subject: str = "math_prof") -> int:
    """Тестовый балл по первичному. Выше максимума — потолок шкалы."""
    if subject != "math_prof":
        return 0
    if primary >= MAX_PRIMARY:
        return MATH_PROF_SCALE[MAX_PRIMARY]
    return MATH_PROF_SCALE.get(max(0, primary), 0)
